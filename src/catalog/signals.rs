pub fn lookup_signal(code: &str) -> Option<&'static SignalRule> {
    SIGNAL_RULES.iter().find(|rule| rule.code == code)
}

pub fn by_domain(domain: &str) -> impl Iterator<Item = &'static SignalRule> + '_ {
    SIGNAL_RULES.iter().filter(move |rule| rule.domain == domain)
}

pub fn by_subject(subject: &str) -> impl Iterator<Item = &'static SignalRule> + '_ {
    SIGNAL_RULES.iter().filter(move |rule| rule.subject == subject)
}

pub fn retryable_codes() -> impl Iterator<Item = &'static str> {
    SIGNAL_RULES.iter().filter(|rule| rule.retryable).map(|rule| rule.code)
}

pub fn total_domain_weight(domain: &str) -> u32 {
    by_domain(domain).map(|rule| rule.weight as u32).sum()
}
